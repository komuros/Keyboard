import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.tasks.KotlinCompile

plugins {
    alias(libs.plugins.android)
}

android {
    compileSdk = project.libs.versions.app.build.compileSDKVersion.get().toInt()

    namespace = "org.fossify.dictionnary"

    defaultConfig {
        applicationId = "org.fossify.dictionnary"
        minSdk = project.libs.versions.app.build.minimumSDK.get().toInt()
        targetSdk = project.libs.versions.app.build.targetSDK.get().toInt()
        versionCode = 1
        versionName = "1.0"
        vectorDrawables.useSupportLibrary = true
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    sourceSets {
        getByName("main").java.directories.add("src/main/kotlin")
    }
    // bundle the pre-built dictionaries (dictionnary/dictionaries, generated by
    // tools/generate_dictionaries.py) in debug builds only, via the
    // src/debug/assets/dictionaries symlink, so the app can serve them offline;
    // release builds download them from the repository instead. Keeps the release
    // APK free of the ~13 MB of JSON files.

    compileOptions {
        val currentJavaVersionFromLibs = JavaVersion.valueOf(libs.versions.app.build.javaVersion.get())
        sourceCompatibility = currentJavaVersionFromLibs
        targetCompatibility = currentJavaVersionFromLibs
    }

    tasks.withType<KotlinCompile> {
        compilerOptions.jvmTarget.set(
            JvmTarget.fromTarget(project.libs.versions.app.build.kotlinJVMTarget.get())
        )
    }

    lint {
        checkReleaseBuilds = false
        abortOnError = false
    }
}
